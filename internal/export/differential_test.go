// The differential test: the point of the whole port.
//
// The bash implementation talks to tests/fake/c8y; this one talks to an httptest
// server. Both are driven from the same fixture, and the object bodies the Go
// side serves are generated by invoking the fake itself - so the two really do
// receive identical bytes, and any difference in the artefacts is a difference
// in behaviour rather than in the test harness.
//
// If this fails, one of the two implementations changed. That is exactly the
// signal worth having.

func requireBashAndJq(t *testing.T) {
	t.Helper()
	for _, tool := range []string{"bash", "jq"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s is not installed, so the bash implementation cannot be run", tool)
		}
	}
}

// runBashExport drives commands/export through the fake c8y and returns the
// output directory and its stderr.
func runBashExport(t *testing.T, fixture string, args ...string) (string, string) {
	t.Helper()

	repo := testfixture.RepoRoot()
	work := t.TempDir()
	rec := filepath.Join(work, "rec")
	if err := os.MkdirAll(rec, 0o755); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(work, "A")

	argv := append([]string{filepath.Join(repo, "commands", "export"),
		"--output-directory", out}, args...)
	cmd := exec.Command("bash", argv...)
	cmd.Dir = work
	cmd.Env = append(os.Environ(),
		"PATH="+filepath.Join(repo, "tests", "fake")+string(os.PathListSeparator)+os.Getenv("PATH"),
		"FAKE_C8Y_REC="+rec,
		"FAKE_C8Y_HIERARCHY="+testfixture.FixturePath(fixture),
	)

	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		t.Fatalf("bash export failed: %v\n%s", err, stderr.String())
	}
	return out, stderr.String()
}

// objectBodiesFromFake asks the fake for each managed object exactly as the bash
// export asks for it, so the Go server can hand back the same bytes.
func objectBodiesFromFake(t *testing.T, fixture string, ids []string) map[string][]byte {
	t.Helper()

	repo := testfixture.RepoRoot()
	work := t.TempDir()
	rec := filepath.Join(work, "rec")
	if err := os.MkdirAll(rec, 0o755); err != nil {
		t.Fatal(err)
	}

	bodies := map[string][]byte{}
	for _, id := range ids {
		target := filepath.Join(work, "object-"+id+".json")
		cmd := exec.Command(filepath.Join(repo, "tests", "fake", "c8y"),
			"inventory", "get", "--id", id, "--outputFileRaw", target, "--nullInput")
		cmd.Env = append(os.Environ(),
			"FAKE_C8Y_REC="+rec,
			"FAKE_C8Y_HIERARCHY="+testfixture.FixturePath(fixture),
		)
		cmd.Stdin = strings.NewReader("")
		if err := cmd.Run(); err != nil {
			t.Fatalf("fake c8y could not produce object %s: %v", id, err)
		}
		body, err := os.ReadFile(target)
		if err != nil {
			t.Fatal(err)
		}
		bodies[id] = body
	}
	return bodies
}

// runGoExport drives the Go export against a server replaying those bodies.
func runGoExport(t *testing.T, fixture string, opts export.Options) (string, string) {
	t.Helper()

	server := testfixture.New(t, fixture)
	for id, body := range objectBodiesFromFake(t, fixture, server.IDs()) {
		server.SetObjectBody(id, body)
	}

	work := t.TempDir()
	sessionPath := server.WriteSessionFile(t, work, "fixture.json")
	s, err := session.Read(sessionPath)
	if err != nil {
		t.Fatal(err)
	}
	client, err := c8yclient.New(s, "")
	if err != nil {
		t.Fatal(err)
	}

	out := filepath.Join(work, "B")
	opts.OutputDirectory = out

	var stderr bytes.Buffer
	if err := export.New(client, &stderr, opts).Run(context.Background()); err != nil {
		t.Fatalf("go export failed: %v\n%s", err, stderr.String())
	}
	return out, stderr.String()
}

// compareDirectories fails with a readable account of every difference.
func compareDirectories(t *testing.T, a, b string) {
	t.Helper()

	namesA := fileNames(t, a)
	namesB := fileNames(t, b)

	if strings.Join(namesA, "\n") != strings.Join(namesB, "\n") {
		t.Fatalf("the two exports wrote different files\nbash:\n  %s\ngo:\n  %s",
			strings.Join(namesA, "\n  "), strings.Join(namesB, "\n  "))
	}

	for _, name := range namesA {
		contentA, err := os.ReadFile(filepath.Join(a, name))
		if err != nil {
			t.Fatal(err)
		}
		contentB, err := os.ReadFile(filepath.Join(b, name))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(contentA, contentB) {
			t.Errorf("%s differs\nbash (%d bytes):\n%s\ngo (%d bytes):\n%s",
				name, len(contentA), contentA, len(contentB), contentB)
		}
	}
}

func fileNames(t *testing.T, dir string) []string {
	t.Helper()
	var names []string
	err := filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		rel, relErr := filepath.Rel(dir, path)
		if relErr != nil {
			return relErr
		}
		names = append(names, rel)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	// filepath.Walk is already lexical, so this stays comparable
	return names
}

// normaliseStderr replaces the output directory, which is the only thing that
// legitimately differs between the two runs.
func normaliseStderr(text, dir string) string {
	text = strings.ReplaceAll(text, dir, "<out>")
	// the bash side is given a relative path, the Go side an absolute one
	return strings.ReplaceAll(text, "./A", "<out>")
}

func TestDifferentialDefaultChildTypes(t *testing.T) {
	requireBashAndJq(t)

	bashDir, bashErr := runBashExport(t, "hierarchy.json", "--rootId", "1")
	goDir, goErr := runGoExport(t, "hierarchy.json", export.Options{
		RootID: "1", ChildTypes: export.DefaultChildTypes})

	compareDirectories(t, bashDir, goDir)

	if got, want := normaliseStderr(goErr, goDir), normaliseStderr(bashErr, bashDir); got != want {
		t.Errorf("stderr differs\nbash:\n%s\ngo:\n%s", want, got)
	}
}

