// exportThenRegister exports the fixture and registers its devices back into the
// same server, which stands in for both tenants. Registration is the phase that
// runs *before* an import, so nothing here imports anything.
func exportThenRegister(t *testing.T, opts registration.Options) (*testfixture.Server, *registration.Registrar, string) {
	t.Helper()

	server := testfixture.New(t, "hierarchy.json")
	work := t.TempDir()
	s := server.ReadSession(t, work, "fixture.json")
	client, err := c8yclient.New(s, "")
	if err != nil {
		t.Fatal(err)
	}

	out := filepath.Join(work, "export")
	var exportErr bytes.Buffer
	if err := export.New(client, &exportErr, export.Options{
		RootID: "1", OutputDirectory: out, ChildTypes: export.DefaultChildTypes,
	}).Run(context.Background()); err != nil {
		t.Fatalf("export failed: %v\n%s", err, exportErr.String())
	}

	opts.InputDirectory = out
	if opts.Tenant == "" {
		opts.Tenant = "t1234567890"
	}
	var stderr bytes.Buffer
	return server, registration.New(client, &stderr, opts), out
}

func TestPlanCoversOnlyDevicesWithAnIdentity(t *testing.T) {
	_, registrar, _ := exportThenRegister(t, registration.Options{})

	plan, err := registrar.Plan()
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Records) == 0 {
		t.Fatal("the plan covers no devices at all")
	}
	for _, record := range plan.Records {
		if record.ExternalID == "" || record.ExternalType == "" {
			t.Errorf("planned a record with no identity: %+v", record)
		}
	}
	// Every skip carries a reason, because a device that gets no credential is a
	// device that will not reconnect and the operator has to hear why.
	for _, skipped := range plan.Skipped {
		if skipped.Reason == "" {
			t.Errorf("object %s was skipped with no reason", skipped.SourceID)
		}
	}
}

// Passwords are not generated by Plan: a caller can print a plan and ask before
// anything exists, and no secret is created for a run that is then abandoned.
func TestPlanGeneratesNoPasswords(t *testing.T) {
	_, registrar, _ := exportThenRegister(t, registration.Options{})

	plan, err := registrar.Plan()
	if err != nil {
		t.Fatal(err)
	}
	for _, record := range plan.Records {
		if record.Password != "" {
			t.Errorf("Plan generated a password for %s", record.ExternalID)
		}
	}
}

func TestRunRegistersEveryPlannedDevice(t *testing.T) {
	server, registrar, _ := exportThenRegister(t, registration.Options{})

	credentials, err := registrar.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	rows := server.Registrations()
	if len(rows) != len(credentials) {
		t.Fatalf("sent %d rows but got %d credentials", len(rows), len(credentials))
	}
	if len(rows) == 0 {
		t.Fatal("nothing was registered")
	}
	for _, row := range rows {
		if row.AuthType != "BASIC" {
			t.Errorf("%s was registered with auth type %q", row.ExternalID, row.AuthType)
		}
		if len(row.Password) != registration.PasswordLength {
			t.Errorf("%s got a %d character password", row.ExternalID, len(row.Password))
		}
	}
}

// The password in the credentials file has to be the one that was sent, or the
// operator distributes something that does not authenticate.
func TestCredentialsMatchWhatWasSent(t *testing.T) {
	server, registrar, _ := exportThenRegister(t, registration.Options{})

	credentials, err := registrar.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	sent := map[string]string{}
	for _, row := range server.Registrations() {
		sent[row.ExternalID] = row.Password
	}
	for _, credential := range credentials {
		if sent[credential.ExternalID] != credential.Password {
			t.Errorf("%s was registered with one password and issued another", credential.ExternalID)
		}
		if want := "device_" + credential.ExternalID; credential.Username != want {
			t.Errorf("username for %s is %q, want %q", credential.ExternalID, credential.Username, want)
		}
		if credential.Tenant != "t1234567890" {
			t.Errorf("credential for %s names tenant %q", credential.ExternalID, credential.Tenant)
		}
	}
}

// Every password distinct: one device's credential must not authenticate as
// another.
func TestEveryDeviceGetsItsOwnPassword(t *testing.T) {
	_, registrar, _ := exportThenRegister(t, registration.Options{})

	credentials, err := registrar.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	seen := map[string]string{}
	for _, credential := range credentials {
		if other, clash := seen[credential.Password]; clash {
			t.Fatalf("%s and %s share a password", other, credential.ExternalID)
		}
		seen[credential.Password] = credential.ExternalID
	}
}

// The marker has to arrive under the name the importer will later query for with
// $filter=has(...), and as a dotted column so the platform stores it as an
// object rather than a string.
func TestRunStampsTheRunMarker(t *testing.T) {
	const marker = "c8y_DeviceMigration_20260908T101112Z_ab12cd"

	server, registrar, _ := exportThenRegister(t, registration.Options{Marker: marker})

	if _, err := registrar.Run(context.Background()); err != nil {
		t.Fatal(err)
	}
	header := server.RegistrationHeader()
	if got := header[len(header)-1]; got != marker+".phase" {
		t.Fatalf("marker column is %q, want %q", got, marker+".phase")
	}
	for _, row := range server.Registrations() {
		if got := row.Fragments[marker+".phase"]; got != registration.PhaseRegistered {
			t.Errorf("%s carries phase %q, want %q", row.ExternalID, got, registration.PhaseRegistered)
		}
	}
}

// What actually arrived at the endpoint, through the whole path rather than at
// the unit level: the delimiter this tool chose and the columns it leaves out.
// The fixture accepts either delimiter, as the platform does, so this pins the
// choice without asserting a restriction that does not exist.
func TestRunSendsACommaSeparatedFile(t *testing.T) {
	server, registrar, _ := exportThenRegister(t, registration.Options{})

	if _, err := registrar.Run(context.Background()); err != nil {
		t.Fatalf("the endpoint refused the registration file: %v", err)
	}
	if got := server.RegistrationDelimiter(); got != ',' {
		t.Errorf("the file arrived separated by %q, want a comma", got)
	}
	header := server.RegistrationHeader()
	if len(header) < 6 {
		t.Fatalf("header has %d columns: %v", len(header), header)
	}
	for _, unwanted := range []string{"ICCID", "TENANT", "PATH", "com_cumulocity_model_Agent.active"} {
		for _, column := range header {
			if column == unwanted {
				t.Errorf("header still carries %s: %v", unwanted, header)
			}
		}
	}
}

// A refused row must not produce a credential, must be reported, and must not
// cost the credentials of the devices that did register - re-running to recover
// them would rotate the passwords of the ones that were fine.
func TestRefusedRowsAreReportedWithoutLosingTheRest(t *testing.T) {
	server, registrar, _ := exportThenRegister(t, registration.Options{})

	plan, err := registrar.Plan()
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Records) < 2 {
		t.Skipf("fixture has %d registrable devices, need at least 2", len(plan.Records))
	}
	refused := plan.Records[0].ExternalID
	server.RefuseRegistration("Error during password validation.", refused)

	credentials, err := registrar.Run(context.Background())

	var partial *registration.PartialError
	if !errors.As(err, &partial) {
		t.Fatalf("error is %v, want a *PartialError", err)
	}
	if len(partial.Failed) != 1 || partial.Failed[0].ExternalID != refused {
		t.Fatalf("PartialError names %+v, want just %s", partial.Failed, refused)
	}
	// Verbatim, because this endpoint answers causes that have nothing to do
	// with passwords with exactly this text.
	if partial.Failed[0].Reason != "Error during password validation." {
		t.Errorf("reason is %q, want the platform's own text", partial.Failed[0].Reason)
	}
	if len(credentials) != len(plan.Records)-1 {
		t.Fatalf("got %d credentials, want %d", len(credentials), len(plan.Records)-1)
	}
	for _, credential := range credentials {
		if credential.ExternalID == refused {
			t.Errorf("a credential was issued for the refused device %s", refused)
		}
	}
}

// A CREDENTIAL_UPDATED row means the target already knew the id: nothing was
// created, the object was left alone, and an existing device's password was
// replaced.
//
// Check refuses that before anything is generated, so a row arriving here means
// the target gained the identity between the lookup and the upload. The device
// it belongs to is the target tenant's, not this migration's, so its new
// credential is reported as a failure rather than handed over - the same answer
// the check gives a moment earlier, and the reason there is no flag to ask for
// the other one.
func TestRotatedRowsAreRefusedRatherThanHandedOver(t *testing.T) {
	server, registrar, _ := exportThenRegister(t, registration.Options{})

	plan, err := registrar.Plan()
	if err != nil {
		t.Fatal(err)
	}
	rotated := plan.Records[0].ExternalID
	server.RotateRegistration(rotated)

	credentials, err := registrar.Run(context.Background())

	var partial *registration.PartialError
	if !errors.As(err, &partial) {
		t.Fatalf("error is %v, want a *PartialError", err)
	}
	if registrar.Rotated() != 1 {
		t.Errorf("Rotated() is %d, want 1", registrar.Rotated())
	}
	for _, credential := range credentials {
		if credential.ExternalID == rotated {
			t.Errorf("a credential was handed over for %s, whose password belonged to a "+
				"device the target already had", rotated)
		}
	}
	// The devices that did register are still handed over: their credentials
	// exist only in this response.
	if len(credentials) != len(plan.Records)-1 {
		t.Errorf("got %d credentials, want the %d devices that did register",
			len(credentials), len(plan.Records)-1)
	}
}

func TestRunReportsSkippedObjects(t *testing.T) {
	server := testfixture.New(t, "hierarchy.json")
	work := t.TempDir()
	s := server.ReadSession(t, work, "fixture.json")
	client, err := c8yclient.New(s, "")
	if err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(work, "export")
	var exportErr bytes.Buffer
	if err := export.New(client, &exportErr, export.Options{
		RootID: "1", OutputDirectory: out, ChildTypes: export.DefaultChildTypes,
	}).Run(context.Background()); err != nil {
		t.Fatal(err)
	}

	var stderr bytes.Buffer
	registrar := registration.New(client, &stderr, registration.Options{
		InputDirectory: out, Tenant: "t1234567890",
	})
	if _, err := registrar.Run(context.Background()); err != nil {
		t.Fatal(err)
	}
	plan, err := registrar.Plan()
	if err != nil {
		t.Fatal(err)
	}
	for _, skipped := range plan.Skipped {
		if !strings.Contains(stderr.String(), skipped.SourceID) {
			t.Errorf("skipped object %s was not reported:\n%s", skipped.SourceID, stderr.String())
		}
	}
}

